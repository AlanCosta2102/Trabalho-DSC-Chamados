CREATE TABLE setores (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         nome VARCHAR(100) NOT NULL,
                         sigla VARCHAR(10) NOT NULL,
                         CONSTRAINT uk_setor_sigla UNIQUE (sigla)
);

CREATE TABLE categorias (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            nome VARCHAR(100) NOT NULL,
                            descricao VARCHAR(500),
                            setor_id BIGINT NOT NULL,
                            CONSTRAINT fk_categoria_setor
                                FOREIGN KEY (setor_id) REFERENCES setores(id)
);

CREATE TABLE usuarios (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          nome VARCHAR(150) NOT NULL,
                          email VARCHAR(180) NOT NULL,
                          matricula VARCHAR(30) NOT NULL,
                          tipo VARCHAR(20) NOT NULL,
                          setor_id BIGINT,
                          CONSTRAINT uk_usuario_email UNIQUE (email),
                          CONSTRAINT uk_usuario_matricula UNIQUE (matricula),
                          CONSTRAINT fk_usuario_setor
                              FOREIGN KEY (setor_id) REFERENCES setores(id),
                          CONSTRAINT ck_usuario_tipo
                              CHECK (tipo IN ('SOLICITANTE', 'TECNICO'))
);

CREATE TABLE chamados (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          titulo VARCHAR(150) NOT NULL,
                          descricao TEXT NOT NULL,
                          local VARCHAR(150) NOT NULL,
                          prioridade VARCHAR(20) NOT NULL DEFAULT 'MEDIA',
                          status VARCHAR(30) NOT NULL DEFAULT 'ABERTO',
                          data_abertura TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                          data_fechamento TIMESTAMP,
                          solucao TEXT,
                          solicitante_id BIGINT NOT NULL,
                          categoria_id BIGINT NOT NULL,
                          tecnico_id BIGINT,
                          CONSTRAINT fk_chamado_solicitante
                              FOREIGN KEY (solicitante_id) REFERENCES usuarios(id),
                          CONSTRAINT fk_chamado_categoria
                              FOREIGN KEY (categoria_id) REFERENCES categorias(id),
                          CONSTRAINT fk_chamado_tecnico
                              FOREIGN KEY (tecnico_id) REFERENCES usuarios(id),
                          CONSTRAINT ck_chamado_prioridade
                              CHECK (prioridade IN ('BAIXA', 'MEDIA', 'ALTA')),
                          CONSTRAINT ck_chamado_status
                              CHECK (status IN (
                                                'ABERTO', 'EM_ATENDIMENTO', 'RESOLVIDO', 'CANCELADO'
                                  ))
);

CREATE TABLE interacoes (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            texto TEXT NOT NULL,
                            data_hora TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                            chamado_id BIGINT NOT NULL,
                            autor_id BIGINT NOT NULL,
                            CONSTRAINT fk_interacao_chamado
                                FOREIGN KEY (chamado_id) REFERENCES chamados(id),
                            CONSTRAINT fk_interacao_autor
                                FOREIGN KEY (autor_id) REFERENCES usuarios(id)
);

CREATE INDEX idx_chamado_status ON chamados(status);
CREATE INDEX idx_chamado_prioridade ON chamados(prioridade);
CREATE INDEX idx_chamado_categoria ON chamados(categoria_id);
CREATE INDEX idx_chamado_solicitante ON chamados(solicitante_id);
CREATE INDEX idx_chamado_tecnico ON chamados(tecnico_id);
CREATE INDEX idx_interacao_chamado ON interacoes(chamado_id);